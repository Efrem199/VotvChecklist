import { test } from 'node:test';
import assert from 'node:assert/strict';
import { englishSaveError } from '../src/data/en/saveErrors';

test('save editor errors retain important details in English', () => {
 assert.equal(englishSaveError('Это не файл GVAS.'), 'This is not a GVAS file.');
 assert.equal(englishSaveError('Неизвестный тип свойства: Foo'), 'Unknown property type: Foo');
 assert.match(englishSaveError('Версия 0.10.0 не поддерживается: только семейство 0.9.0 (0.9.0n не отличима от других патчей по этому полю).'), /0\.10\.0.*unsupported.*0\.9\.0/);
 assert.match(englishSaveError('неизвестная ошибка'), /Details \(Russian\): неизвестная ошибка/);
});

