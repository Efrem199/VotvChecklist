import { test } from 'node:test';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { build } from 'esbuild';
import { rm } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import React from 'react';
import { ACHIEVEMENTS_KEY } from '../src/lib/achievements';
import { PROFILES_KEY } from '../src/lib/profiles';

test('достижения, профили, спойлеры, глобальный поиск и переходы по сайту', async () => {
 const dom=new JSDOM('<!doctype html><html><body></body></html>',{url:'https://example.com/#/achievements'});
 Object.assign(globalThis,{window:dom.window,document:dom.window.document,HTMLElement:dom.window.HTMLElement,Element:dom.window.Element,localStorage:dom.window.localStorage,requestAnimationFrame:(fn:()=>void)=>setTimeout(fn,0)});
 dom.window.localStorage.setItem('votv-checklist-language', 'ru');
 dom.window.requestAnimationFrame=(fn)=>setTimeout(fn,0) as unknown as number;
 dom.window.scrollTo=()=>{}; dom.window.HTMLElement.prototype.scrollIntoView=()=>{};
 dom.window.confirm=()=>true; dom.window.prompt=()=> 'Другой профиль';
 const out='.achievements-test-bundle.mjs';
 try {
  await build({entryPoints:['src/App.tsx'],bundle:true,platform:'node',format:'esm',packages:'external',loader:{'.jpg':'dataurl'},outfile:out,logLevel:'silent'});
  const {default:App}=await import(pathToFileURL(process.cwd()+'/'+out).href);
  const {render,fireEvent,cleanup,waitFor,within}=await import('@testing-library/react');
  const view=render(React.createElement(App));
  const navigate=(hash:string)=>{dom.window.history.pushState(null,'',hash);fireEvent(dom.window,new dom.window.Event('hashchange'))};
  const mark=(name:RegExp)=>view.getByRole('checkbox',{name}) as HTMLInputElement;
  assert.ok(view.getByRole('heading',{name:'ДОСТИЖЕНИЯ'}));
  assert.equal(view.queryByRole('heading',{name:'Super burger finder'}),null);
  assert.equal(view.queryByText(/Найдите каждый сэндвич/),null);
  assert.equal(view.queryByAltText('Пример: сэндвич в серверной базы'),null);
  fireEvent.change(view.getByLabelText('Поиск достижений'),{target:{value:'Upgrade'}});
  const upgradeCard=view.getByRole('heading',{name:'Upgrade'}).closest('li')!;
  const guideLink=within(upgradeCard).getByRole('link',{name:/Полный гайд Kerfur-Omega в журнале/});
  assert.equal(guideLink.getAttribute('href'),'#/journal?section=kerfur-omega');
  assert.equal(within(upgradeCard).queryByText(/14 пластикового/),null);
  navigate(guideLink.getAttribute('href')!);
  const journalGuide=within(view.getByRole('region',{name:'Гайд Kerfur-Omega'}));
  await waitFor(()=>assert.ok(journalGuide.getByText(/14 пластикового, 7 металлического, 8 электронного/)));
  assert.ok(journalGuide.getByText(/Голова: 1 Kerfur Parts/));
  assert.ok(journalGuide.getByText(/X:405.5, Y:-406.0/));
  const joint=journalGuide.getByAltText('Места коробок шарниров у Romeo') as HTMLImageElement;
  assert.match(joint.closest('li')!.textContent!, /Ball Joints:/);
  assert.equal(joint.getAttribute('loading'), 'lazy');
  assert.equal(joint.getAttribute('src'), 'https://voicesofthevoid.wiki.gg/images/thumb/Item_BallJoint_BoxDigLocations.png/240px-Item_BallJoint_BoxDigLocations.png');
  fireEvent.error(joint); assert.equal(joint.hidden, true);
  assert.ok(journalGuide.getByRole('link',{name:/Места коробок шарниров у Romeo/}));
  assert.match(journalGuide.getByAltText('Готовая голова Kerfur-Omega').closest('li')!.textContent!, /Голова:/);
  const guideDetails=journalGuide.getByText(/Гайд Kerfur-Omega · спойлеры/).closest('details')!;
  guideDetails.open=false; fireEvent(guideDetails,new dom.window.Event('toggle'));
  assert.equal(journalGuide.queryByText(/14 пластикового/),null);
  navigate('#/journal?section=kerfur-omega');
  await waitFor(()=>assert.ok(journalGuide.getByText(/14 пластикового/)));
  navigate('#/achievements?item=upgrade');
  fireEvent.change(view.getByLabelText('Поиск достижений'),{target:{value:''}});
  fireEvent.click(mark(/Получено: Sandbox unlocked/));
  await waitFor(()=>assert.equal(JSON.parse(dom.window.localStorage.getItem(ACHIEVEMENTS_KEY)!).marks.sandbox,true));
  fireEvent.click(view.getByRole('button',{name:'Advancements сохранения'}));
  fireEvent.click(mark(/Получено: Buy Kerfur/));
  await waitFor(()=>assert.equal(JSON.parse(dom.window.localStorage.getItem(PROFILES_KEY)!).profiles[0].state.advancements['adv-kerfur'],true));
  navigate('#/');
  fireEvent.click(view.getByRole('button',{name:'+ новое'}));
  navigate('#/achievements');
  assert.equal(mark(/Получено: Sandbox unlocked/).checked,true);
  fireEvent.click(view.getByRole('button',{name:'Advancements сохранения'}));
  assert.equal(mark(/Получено: Buy Kerfur/).checked,false);
  fireEvent.change(view.getByRole('combobox',{name:'Профиль для гайдов и advancements'}),{target:{value:'default'}});
  assert.equal(mark(/Получено: Buy Kerfur/).checked,true);
  fireEvent.change(view.getByLabelText('Поиск по сайту'),{target:{value:'Super burger finder'}});
  assert.equal(view.queryByRole('link',{name:/Достижение: Super burger finder/}),null);
  fireEvent.click(view.getByRole('checkbox',{name:'Искать и в спойлерах'}));
  assert.ok(view.getByRole('link',{name:/Достижение: Super burger finder/}));
  navigate('#/achievements?item=maid');
  const maidCard=()=>within(view.getByRole('heading',{name:'Maid'}).closest('li')!);
  const maidDetails=maidCard().getByText('Как получить · пошаговый гайд').closest('details')!;
  maidDetails.open=true; fireEvent(maidDetails,new dom.window.Event('toggle'));
  assert.ok(maidCard().getByAltText('Лопата на балке TR2'));
  assert.ok(maidCard().getByAltText('Открытый сейф — результат'));
  fireEvent.click(maidCard().getByRole('checkbox',{name:'Шаг 1 выполнен'}));
  await waitFor(()=>assert.equal(JSON.parse(dom.window.localStorage.getItem(PROFILES_KEY)!).profiles[0].state.plannerSteps['guide:maid:0'],true));
  assert.match(maidCard().getByText(/Выполнено шагов:/).textContent!,/1 \/ 4/);
  const profileSelect=view.getByRole('combobox',{name:'Профиль для гайдов и advancements'}) as HTMLSelectElement;
  const other=[...profileSelect.options].find(o=>o.value!=='default')!.value;
  fireEvent.change(profileSelect,{target:{value:other}});
  assert.equal((maidCard().getByRole('checkbox',{name:'Шаг 1 выполнен'}) as HTMLInputElement).checked,false);
  fireEvent.change(profileSelect,{target:{value:'default'}});
  assert.equal((maidCard().getByRole('checkbox',{name:'Шаг 1 выполнен'}) as HTMLInputElement).checked,true);
  navigate('#/achievements?item=super-burger');
  assert.ok(view.getByRole('heading',{name:'Super burger finder'}));
  assert.equal(view.getByRole('checkbox',{name:'Показать спойлеры'}).checked,true);
  assert.equal(view.getByRole('link',{name:'Связанная коллекция в журнале ↗'}).getAttribute('href'),'#/journal?collection=sandwiches');
  assert.equal(view.queryByText(/Найдите каждый сэндвич/),null);
  assert.equal(view.queryByAltText('Пример: сэндвич в серверной базы'),null);
  const details=view.getByText('Как получить · пошаговый гайд').closest('details')!;
  details.open=true; fireEvent(details,new dom.window.Event("toggle"));
  assert.ok(view.getByText(/Найдите каждый сэндвич/));
  const sandwich = view.getByAltText('Сэндвич 01: место находки');
  assert.match(sandwich.closest('li')!.textContent!, /Сэндвич 01:/);
  const guideImage=view.getByAltText('Пример: сэндвич в серверной базы') as HTMLImageElement;
  fireEvent.error(guideImage); assert.equal(guideImage.hidden,true);
  assert.ok(view.getByRole('link',{name:/Пример: сэндвич в серверной базы/}));
  details.open=false; fireEvent(details,new dom.window.Event("toggle"));
  assert.equal(view.queryByAltText('Пример: сэндвич в серверной базы'),null);
  fireEvent.click(view.getByRole('checkbox',{name:'Показать спойлеры'}));
  assert.equal(view.queryByText('Как получить · пошаговый гайд'),null);
  fireEvent.click(view.getByRole('checkbox',{name:'Показать спойлеры'}));
  navigate('#/journal?collection=sandwiches');
  assert.equal(within(view.getByRole('region',{name:'Коллекции'})).getByRole('button',{name:/Сэндвичи/}).getAttribute('aria-pressed'),'true');
  assert.ok(document.querySelector('#loc-burger-server'));
  fireEvent.click(within(view.getByRole('navigation',{name:'Быстрый переход к категориям'})).getByRole('button',{name:'Тарелки'}));
  assert.equal(within(view.getByRole('region',{name:'Коллекции'})).getByRole('button',{name:'Все точки'}).getAttribute('aria-pressed'),'true');
  assert.ok(document.querySelector('#loc-dish-b'));
  fireEvent.change(view.getByLabelText('Поиск по сайту'),{target:{value:'sv.ping'}});
  assert.ok(view.getByRole('link',{name:/Команда: sv.ping/}));
  navigate('#/fun?q=sv.ping');
  assert.equal((view.getByLabelText('Найти команду') as HTMLInputElement).value,'sv.ping');
  assert.ok(view.getByText('sv.ping'));
  navigate('#/journal?loc=hole');
  await waitFor(()=>assert.equal(view.getByRole('button',{name:'Карточка: Яма'}).getAttribute('aria-expanded'),'true'));
  fireEvent.click(view.getByRole('button',{name:'Карточка: Яма'}));
  assert.equal(view.getByRole('button',{name:'Карточка: Яма'}).getAttribute('aria-expanded'),'false');
  navigate('#/journal?loc=hole');
  await waitFor(()=>assert.equal(view.getByRole('button',{name:'Карточка: Яма'}).getAttribute('aria-expanded'),'true'));
  fireEvent.change(view.getByLabelText('Поиск по сайту'),{target:{value:'а'}});
  const showAll=view.getByRole('button',{name:/Показать все/});
  fireEvent.click(showAll);
  assert.equal(showAll.getAttribute('aria-expanded'),'true');
  cleanup();
  dom.window.localStorage.setItem(ACHIEVEMENTS_KEY,'{broken');
  dom.window.location.hash='#/achievements';
  const damaged=render(React.createElement(App));
  assert.ok(damaged.getByRole('alert').textContent?.includes('Не удалось прочитать'));
  assert.equal((damaged.getByRole('checkbox',{name:/Получено: Sandbox unlocked/}) as HTMLInputElement).disabled,true);
  assert.equal(dom.window.localStorage.getItem(ACHIEVEMENTS_KEY),'{broken');
  cleanup();
 } finally { await rm(out,{force:true}); dom.window.close(); }
});
