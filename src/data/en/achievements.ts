/** Returns undefined for an untranslated entry, rather than silently inventing a translation. */
export function englishAchievement(source: Achievement): Achievement | undefined {
 const condition = conditions[source.id];
 const points = /^(\d+) очк(?:о|а|ов)\.$/.exec(source.reward);
 const reward = rewards[source.reward] ?? (points ? `${points[1]} points.` : undefined);
 if (!condition || !reward) return undefined;
 return { ...source, condition, reward };
}

export const ACHIEVEMENTS_EN = ACHIEVEMENTS.map(englishAchievement);
